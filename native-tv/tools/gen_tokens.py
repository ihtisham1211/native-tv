#!/usr/bin/env python3
"""Generate native-tv/src/ui/kit/tokens.hpp, palette.cpp and src/core/themes.hpp from
design/tokens.json, design/themes/*.json and design/metrics.json.

tokens.json is the n-google-tv theme. Each file in design/themes/ is another theme: it names only
the colours that differ, and the rest come from tokens.json.

`--check` regenerates in memory and exits 1 when a committed file is stale,
so the TV client, the CSS prototype and the phone pages share one set of numbers.
"""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "design" / "tokens.json"
THEMES = ROOT / "design" / "themes"
METRICS = ROOT / "design" / "metrics.json"
OUTPUT = ROOT / "src" / "ui" / "kit" / "tokens.hpp"
PALETTE_OUTPUT = ROOT / "src" / "ui" / "kit" / "palette.cpp"
THEME_LIST_OUTPUT = ROOT / "src" / "core" / "themes.hpp"

PREAMBLE = """\
// Generated by tools/gen_tokens.py from design/tokens.json, design/themes and design/metrics.json.
// Do not edit.
#pragma once
#include "ui/scene.hpp"
#include <string>

namespace nativetv {
namespace kit {
constexpr Color rgb(unsigned value, float alpha = 1) {
    return {((value >> 16) & 255) / 255.0f, ((value >> 8) & 255) / 255.0f, (value & 255) / 255.0f,
            alpha};
}
// px and line are TV px at 1920x1080; tracking is in em.
struct TypeStyle {
    float px, line;
    int weight;
    float tracking;
};
// A shadow recipe from the elevation tokens; the scene's own Shadow also carries a colour.
struct ShadowRecipe {
    float dy, blur, alpha;
};
struct Bezier {
    float x1, y1, x2, y2;
};
struct SpringTuning {
    float stiffness, dampingRatio;
};
"""


def number(value):
    """A C++ float literal: integers stay bare, fractions get an f suffix."""
    if isinstance(value, int) or float(value).is_integer():
        return str(int(value))
    return repr(float(value)) + "f"


def colour(hex_value, alpha=None):
    body = "0x" + hex_value.lstrip("#").upper()
    return "rgb(%s)" % body if alpha is None else "rgb(%s, %s)" % (body, number(alpha))


def identifier(text):
    """'tile 7 (row 2)' -> 'tile7Row2'; the first word is lower-cased."""
    words = re.findall(r"[A-Za-z0-9]+", text)
    return words[0].lower() + "".join(word[0].upper() + word[1:] for word in words[1:])


def emit_namespace(name, lines, body):
    lines.append("namespace %s {" % name)
    lines.extend(body)
    lines.append("} // namespace %s" % name)


def style(entry):
    return "{%s, %s, %d, %s}" % (number(entry["px"]), number(entry["line"]), entry["weight"],
                                 number(entry["tracking"]))


def palette_slots(tokens):
    """Every colour a theme can set, in the order Palette declares them: (group, key)."""
    slots = ([("color", key) for key in tokens["color"]]
             + [("colorFloat", key) for key in tokens["colorFloat"]]
             + [("colorAlpha", key) for key in tokens["colorAlpha"]]
             + [("focusRingColor", None)]
             + [("look", key) for key in tokens["look"]])
    names = [slot_name(group, key) for group, key in slots]
    if len(set(names)) != len(names):
        sys.exit("tokens.json: two palette entries share a name")
    return slots


def slot_name(group, key):
    return "focusRingColor" if group == "focusRingColor" else key


def slot_type(tokens, group, key):
    if group != "look":
        return "Color"
    return "bool" if isinstance(tokens["look"][key], bool) else "float"


def slot_literal(group, value):
    if group == "colorFloat":
        return "{%s, %s, %s, 1}" % tuple(number(part) for part in value)
    if group == "colorAlpha":
        return colour(*value)
    if group == "look":
        return ("true" if value else "false") if isinstance(value, bool) else number(value)
    return colour(value)


THEME_KEYS = {"id", "name", "summary", "color", "colorFloat", "colorAlpha", "focusRingColor", "look"}


def load_themes(tokens, theme_dir):
    """n-google-tv from tokens.json first, then design/themes/*.json by file name."""
    slots = palette_slots(tokens)
    base = {("focusRingColor", None): tokens["elevation"]["focusRing"]["color"]}
    for group, key in slots:
        if group != "focusRingColor":
            base[(group, key)] = tokens[group][key]
    themes = [dict(tokens["theme"], slots=base)]
    for path in sorted(theme_dir.glob("*.json")):
        theme = json.loads(path.read_text())
        extra = set(theme) - THEME_KEYS
        if extra:
            sys.exit("%s: unknown key %s" % (path.name, ", ".join(sorted(extra))))
        if not re.fullmatch(r"n-[a-z0-9]+(-[a-z0-9]+)*", theme["id"]) or theme["id"] != path.stem:
            sys.exit("%s: the id must be the file name, as n-name" % path.name)
        resolved = dict(base)
        for group in ("color", "colorFloat", "colorAlpha", "look"):
            for key, value in theme.get(group, {}).items():
                if (group, key) not in resolved:
                    sys.exit("%s: %s.%s is not an entry of tokens.json" % (path.name, group, key))
                if group == "look" and isinstance(value, bool) != isinstance(tokens["look"][key], bool):
                    sys.exit("%s: look.%s must be a %s" % (path.name, key, "boolean"
                             if isinstance(tokens["look"][key], bool) else "number"))
                resolved[(group, key)] = value
        if "focusRingColor" in theme:
            resolved[("focusRingColor", None)] = theme["focusRingColor"]
        themes.append(dict(id=theme["id"], name=theme["name"], summary=theme["summary"], slots=resolved))
    ids = [theme["id"] for theme in themes]
    if len(set(ids)) != len(ids):
        sys.exit("two themes share an id")
    return themes


def emit_palettes(out, tokens, themes):
    slots = palette_slots(tokens)
    out.append("// Every colour a screen draws, once per theme. Screens read them as color::name and "
               "alpha::name,")
    out.append("// which follow the palette in use; useTheme() switches it.")
    out.append("struct Palette {")
    out += ["    %s %s;" % (slot_type(tokens, group, key), slot_name(group, key)) for group, key in slots]
    out.append("};")
    for theme in themes:
        out.append("constexpr Palette %s = {" % identifier(theme["id"]))
        out.append(",\n".join("    " + slot_literal(group, theme["slots"][(group, key)])
                              for group, key in slots))
        out.append("};")
    out.append("struct ThemeInfo {")
    out.append("    const char *id, *name, *summary;")
    out.append("    const Palette *palette;")
    out.append("};")
    out.append("constexpr ThemeInfo themes[] = {")
    out.append(",\n".join("    {%s, %s, %s, &%s}" % (json.dumps(theme["id"]), json.dumps(theme["name"]),
                                                      json.dumps(theme["summary"]), identifier(theme["id"]))
                          for theme in themes))
    out.append("};")
    out.append("constexpr int themeCount = %d;" % len(themes))
    out.append("const Palette &palette();")
    out.append("const char *themeId();")
    out.append("// Switches to the theme with this id; false, and no change, when there is none.")
    out.append("bool useTheme(const std::string &id);")


def generate_palette_source(tokens, themes):
    out = ["// Generated by tools/gen_tokens.py from design/tokens.json and design/themes. Do not edit.",
           '#include "ui/kit/tokens.hpp"',
           "",
           "namespace nativetv {",
           "namespace kit {",
           "namespace {",
           "Palette active = %s;" % identifier(themes[0]["id"]),
           "const ThemeInfo *activeTheme = &themes[0];",
           "} // namespace",
           "const Palette &palette() {",
           "    return active;",
           "}",
           "const char *themeId() {",
           "    return activeTheme->id;",
           "}",
           "bool useTheme(const std::string &id) {",
           "    for (const ThemeInfo &theme : themes) {",
           "        if (id == theme.id) {",
           "            active = *theme.palette;",
           "            activeTheme = &theme;",
           "            return true;",
           "        }",
           "    }",
           "    return false;",
           "}"]
    for namespace, groups in (("color", ("color", "colorFloat")), ("alpha", ("colorAlpha",)),
                              ("elevation", ("focusRingColor",)), ("look", ("look",))):
        out.append("namespace %s {" % namespace)
        out += ["const %s &%s = active.%s;" % (slot_type(tokens, g, key), slot_name(g, key), slot_name(g, key))
                for g, key in palette_slots(tokens) if g in groups]
        out.append("} // namespace %s" % namespace)
    out.append("} // namespace kit")
    out.append("} // namespace nativetv")
    return "\n".join(out) + "\n"


def generate_theme_list(themes):
    """The themes by id and name, for the server and the client's settings (no colours)."""
    out = ["// Generated by tools/gen_tokens.py from design/tokens.json and design/themes. Do not edit.",
           "#pragma once",
           "#include <string>",
           "",
           "namespace nativetv {",
           "// The TV themes. The server keeps one id as `tvTheme`; the first is the default.",
           "struct ThemeChoice {",
           "    const char *id, *name, *summary;",
           "};",
           "constexpr ThemeChoice kThemeChoices[] = {"]
    out.append(",\n".join("    {%s, %s, %s}" % (json.dumps(theme["id"]), json.dumps(theme["name"]),
                                                json.dumps(theme["summary"])) for theme in themes))
    out += ["};",
            "constexpr int kThemeChoiceCount = %d;" % len(themes),
            "constexpr const char *kDefaultTheme = %s;" % json.dumps(themes[0]["id"]),
            "// The choice with this id, or null.",
            "inline const ThemeChoice *findTheme(const std::string &id) {",
            "    for (const ThemeChoice &choice : kThemeChoices)",
            "        if (id == choice.id)",
            "            return &choice;",
            "    return nullptr;",
            "}",
            "} // namespace nativetv"]
    return "\n".join(out) + "\n"


def generate(tokens, metrics, themes):
    out = [PREAMBLE.rstrip("\n")]

    canvas = tokens["canvas"]
    emit_namespace("canvas", out, ["constexpr float %s = %s;" % (key, number(value))
                                   for key, value in canvas.items()])

    emit_palettes(out, tokens, themes)
    emit_namespace("color", out, ["extern const Color &%s;" % key
                                  for key in list(tokens["color"]) + list(tokens["colorFloat"])])
    emit_namespace("alpha", out, ["extern const Color &%s;" % key for key in tokens["colorAlpha"]])
    out.append("// What a theme changes besides colour.")
    emit_namespace("look", out, ["extern const %s &%s;" % (slot_type(tokens, "look", key), key)
                                 for key in tokens["look"]])

    kind = tokens["type"]
    body = ['constexpr const char *family = "%s";' % kind["family"]]
    body += ["constexpr TypeStyle %s = %s;" % (key, style(value))
             for key, value in kind.items() if isinstance(value, dict) and "px" in value]
    emit_namespace("type", out, body)

    emit_namespace("space", out, ["constexpr float x%d = %d;" % (value, value)
                                  for value in tokens["space"]])
    emit_namespace("radius", out, ["constexpr float %s = %s;" % (key, number(value))
                                   for key, value in tokens["radius"].items()])

    elevation = tokens["elevation"]
    ring = elevation["focusRing"]
    shadows = ["constexpr ShadowRecipe %s = {%s, %s, %s};" % (key, number(value["dy"]),
                                                       number(value["blur"]), number(value["alpha"]))
               for key, value in elevation.items() if key != "focusRing"]
    emit_namespace("elevation", out, [
        "constexpr float focusRingWidth = %s;" % number(ring["width"]),
        "extern const Color &focusRingColor;"] + shadows)

    layout = ["constexpr float %s = %s;" % (key, number(value))
              for key, value in tokens["layout"].items()]
    layout += ["constexpr int %s = %d;" % (key, value) for key, value in tokens["count"].items()]
    emit_namespace("layout", out, layout)

    motion = tokens["motion"]
    body = []
    body.append("namespace ms {")
    body += ["constexpr int %s = %d;" % (key, value) for key, value in motion["ms"].items()]
    body.append("constexpr int idleAfter = %d;" % motion["idleAfterMs"])
    body.append("} // namespace ms")
    body.append("namespace ease {")
    for key, value in motion["ease"].items():
        curve = value or [0, 0, 1, 1]
        body.append("constexpr Bezier %s = {%s};" % (key, ", ".join(number(v) for v in curve)))
    body.append("} // namespace ease")
    body.append("namespace spring {")
    body += ["constexpr SpringTuning %s = {%s, %s};" % (key, number(value["k"]), number(value["zeta"]))
             for key, value in motion["spring"].items()]
    body.append("} // namespace spring")
    body.append("namespace scale {")
    body += ["constexpr float %s = %s;" % (key, number(value))
             for key, value in motion["scale"].items()]
    body.append("} // namespace scale")
    body.append("namespace stagger {")
    for key, value in motion["stagger"].items():
        if isinstance(value, list):
            body.append("constexpr int %s[%d] = {%s};" % (key, len(value),
                                                          ", ".join(str(v) for v in value)))
        else:
            body.append("constexpr int %s = %d;" % (key, value))
    body.append("} // namespace stagger")
    emit_namespace("motion", out, body)

    # Boxes measured from the prototype's DOM; the kit's geometry is tested against them.
    body = []
    for page, entries in metrics.items():
        names = {}
        rects = []
        for label, box in entries.items():
            name = identifier(label)
            if name in names:
                sys.exit("metrics.json: '%s' and '%s' both become %s" % (names[name], label, name))
            names[name] = label
            rects.append("constexpr Rect %s = {%s, %s, %s, %s};" % (
                name, number(box["x"]), number(box["y"]), number(box["w"]), number(box["h"])))
        emit_namespace(page, body, rects)
    emit_namespace("metrics", out, body)

    out.append("} // namespace kit")
    out.append("} // namespace nativetv")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail when the committed tokens.hpp differs from the JSON")
    args = parser.parse_args()
    tokens = json.loads(TOKENS.read_text())
    themes = load_themes(tokens, THEMES)
    outputs = {OUTPUT: generate(tokens, json.loads(METRICS.read_text()), themes),
               PALETTE_OUTPUT: generate_palette_source(tokens, themes),
               THEME_LIST_OUTPUT: generate_theme_list(themes)}
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                sys.exit("%s is stale: run python3 native-tv/tools/gen_tokens.py" % path)
        else:
            path.write_text(text)


if __name__ == "__main__":
    main()
